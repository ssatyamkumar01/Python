# Tuple is the immutable.
# Tuple is always declared in parenthesis.
a=(1,1,5,6,77,'Ram','Shyam')
a1=(1,556,12,45,87,456,21,25,36,455)
print(type(a))
print(a)
print(a[4])
print(a.count(1)) # how many time value occures.
print(a.index(77)) # Finds the position of an element.
print(len(a)) # Returns number of elements.
print(max(a1))  # Return maximum value.
print(min(a1)) # Return minimum value.
print(a[1:4]) # We can slice.